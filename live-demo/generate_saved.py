"""Run the exact browser programs and package their real offline results.

Run from any directory: python live-demo/generate_saved.py
Requires scikit-learn 1.6.1 (the pinned Pyodide release uses the same version).
The website itself requires no Python installation.
"""
from contextlib import redirect_stdout
from datetime import datetime, timezone
from pathlib import Path
import hashlib
import io
import json
import sys
import sklearn

# Saved results must match what the browser would compute, so refuse other versions.
EXPECTED_SKLEARN = "1.6.1"
if sklearn.__version__ != EXPECTED_SKLEARN:
    sys.exit(f"Need scikit-learn {EXPECTED_SKLEARN}, found {sklearn.__version__}. "
             "Run: pip install -r live-demo/requirements.txt")

ROOT = Path(__file__).resolve().parent
sources = {key: (ROOT / filename).read_text(encoding="utf-8") for key, filename in
           [("iris", "iris.py"), ("irisResult", "iris-result.py"), ("race", "race.py")]}

def execute(code):
    scope = {}
    output = io.StringIO()
    with redirect_stdout(output):
        exec(compile(code, "<live-demo>", "exec"), scope)
    return dict(scope["_result"], output=output.getvalue())

saved = {
    "generated_at": datetime.now(timezone.utc).isoformat(),
    "sklearn": sklearn.__version__,
    "source_sha256": {key: hashlib.sha256(code.encode()).hexdigest()
                      for key, code in sources.items()},
    "iris": execute(sources["iris"] + "\n" + sources["irisResult"]),
    "race": execute(sources["race"]),
}
(ROOT / "data.js").write_text(
    "// Generated by generate_saved.py from actual local Python runs.\n"
    "window.LiveDemoData = " + json.dumps(dict(sources=sources, saved=saved),
                                         ensure_ascii=True) + ";\n", encoding="utf-8")
print("Iris:", saved["iris"]["accuracy"], saved["iris"]["species"])
for result in saved["race"]["models"]:
    print(result["name"] + ":", result["accuracy"])
